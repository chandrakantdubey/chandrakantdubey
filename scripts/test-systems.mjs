import assert from 'node:assert/strict';
import {BASE_CAPACITY,BASE_RESILIENCE,estimateCapacity,simulateResilience} from '../src/experience/systemsModel.ts';
const base=estimateCapacity(BASE_CAPACITY);
assert.deepEqual(base,estimateCapacity(BASE_CAPACITY));
assert.ok(base.availableRegions===2);
const withCache=estimateCapacity({...BASE_CAPACITY,edgeHit:90});
assert.ok(withCache.dbRps<base.dbRps);
const noCache=estimateCapacity({...BASE_CAPACITY,edgeHit:0});
assert.ok(noCache.rejectedRps>=base.rejectedRps);
const dbCollapse=estimateCapacity({...BASE_CAPACITY,dbReadCapacity:20});
assert.equal(dbCollapse.bottleneck,'database');
assert.ok(dbCollapse.availabilityPct<base.availabilityPct);
const outage=estimateCapacity({...BASE_CAPACITY,edgeHit:0,regionCount:1,failRegion:true});
assert.equal(outage.availableRegions,0);
assert.equal(outage.servedRps,0);
assert.ok(outage.warnings.length>0);
const same=simulateResilience(BASE_RESILIENCE);
assert.deepEqual(same,simulateResilience(BASE_RESILIENCE));
assert.equal(same.ticks.length,60);
assert.ok(same.totalOffered>0&&same.peakQueue>=0);
const hostile=simulateResilience({...BASE_RESILIENCE,retryPolicy:'fixed',circuitBreaker:false,baseRps:600,dependencyCapacity:250});
const defended=simulateResilience({...BASE_RESILIENCE,retryPolicy:'none',circuitBreaker:true,baseRps:600,dependencyCapacity:250});
assert.ok(hostile.peakQueue>=defended.peakQueue);
assert.ok(hostile.retryAmplification>=defended.retryAmplification);
assert.ok(same.ticks.every(t=>t.queue>=0&&t.completed>=0&&t.failed>=0));
console.log('Systems Gallery: cache/DB/region tradeoffs, retry amplification, deterministic traces PASS');
