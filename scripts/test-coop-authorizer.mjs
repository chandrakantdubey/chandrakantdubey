import assert from 'node:assert/strict';
import {validateCoopAction} from '../src/play/coopAuthorizer.js';
import {newCoopGame,beginPacketGame,pairRotateCoop,shieldCoopFault} from '../src/play/packetEngine.js';
const room=beginPacketGame(newCoopGame(30,2),1000);
assert.equal(validateCoopAction('pair',1,room,0),null);
assert.equal(validateCoopAction('pair',1,room,2),null);
assert.match(validateCoopAction('pair',1,room,3),/columns 1–3/);
assert.match(validateCoopAction('pair',2,room,0),/Route Architect/);
assert.match(validateCoopAction('shield',1,room),/Systems Operator/);
assert.equal(validateCoopAction('shield',2,room),null);
assert.match(validateCoopAction('pair',1,room,-1),/columns/);
assert.match(validateCoopAction('pair',1,room,35),/columns/);
assert.match(validateCoopAction('pair',1,room,1.5),/columns/);
assert.match(validateCoopAction('shield',2,{...room,phase:'ready'}),/active/);
assert.match(validateCoopAction('shield',2,{...room,coop:undefined}),/active/);
const noPairs=pairRotateCoop(pairRotateCoop(room,0),2);
assert.match(validateCoopAction('pair',1,noPairs,0),/charges remain/);
const noShields=shieldCoopFault(shieldCoopFault(room));
assert.match(validateCoopAction('shield',2,noShields),/shields remain/);
console.log('Co-op server authorization: role separation, finite charges, phase and index bounds PASS');
